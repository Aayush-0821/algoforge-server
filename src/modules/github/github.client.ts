import { AppError } from "../../errors/app.errors.js";

import { GITHUB_API_URL } from "./github.constants.js";

import type {
  GitHubContentFile,
  GitHubCreateRepositoryResponse,
  GitHubFileResponse,
  GitHubRepository,
} from "./github.types.js";

const USER_AGENT = "AlgoForge";

function getHeaders(accessToken: string) {
  return {
    Authorization: `Bearer ${accessToken}`,
    Accept: "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28",
    "User-Agent": USER_AGENT,
  };
}

async function githubRequest<T>(
  accessToken: string,
  path: string,
  options: RequestInit = {},
): Promise<T> {
  const response = await fetch(`${GITHUB_API_URL}${path}`, {
    ...options,
    headers: {
      ...getHeaders(accessToken),
      ...(options.headers ?? {}),
    },
  });

  if (!response.ok) {
    let message = `GitHub API request failed (${response.status}).`;

    try {
      const body = (await response.json()) as {
        message?: string;
      };

      if (body.message) {
        message = body.message;
      }
    } catch {
      // Keep the generic message.
    }

    throw new AppError(message, 502);
  }

  return (await response.json()) as T;
}

export async function getAuthenticatedGitHubUser(accessToken: string) {
  return githubRequest<{
    id: number;
    login: string;
    avatar_url: string;
    html_url: string;
  }>(accessToken, "/user");
}

export async function getRepository(
  accessToken: string,
  owner: string,
  repository: string,
): Promise<GitHubRepository | null> {
  const response = await fetch(
    `${GITHUB_API_URL}/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}`,
    {
      headers: getHeaders(accessToken),
    },
  );

  if (response.status === 404) {
    return null;
  }

  if (!response.ok) {
    let message = `Failed to fetch GitHub repository (${response.status}).`;

    try {
      const body = (await response.json()) as {
        message?: string;
      };

      if (body.message) {
        message = body.message;
      }
    } catch {
      // Keep generic message.
    }

    throw new AppError(message, 502);
  }

  return (await response.json()) as GitHubRepository;
}

export async function createPrivateRepository(
  accessToken: string,
  repositoryName: string,
): Promise<GitHubCreateRepositoryResponse> {
  return githubRequest<GitHubCreateRepositoryResponse>(accessToken, "/user/repos", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      name: repositoryName,
      description: "Private coding revision vault generated by AlgoForge.",
      private: true,
      has_issues: false,
      has_projects: false,
      has_wiki: false,
      auto_init: true,
    }),
  });
}

export async function getRepositoryFile(
  accessToken: string,
  owner: string,
  repository: string,
  path: string,
): Promise<GitHubContentFile | null> {
  const encodedPath = path.split("/").map(encodeURIComponent).join("/");

  const response = await fetch(
    `${GITHUB_API_URL}/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/contents/${encodedPath}`,
    {
      headers: getHeaders(accessToken),
    },
  );

  if (response.status === 404) {
    return null;
  }

  if (!response.ok) {
    let message = `Failed to fetch GitHub file (${response.status}).`;

    try {
      const body = (await response.json()) as {
        message?: string;
      };

      if (body.message) {
        message = body.message;
      }
    } catch {
      // Keep generic message.
    }

    throw new AppError(message, 502);
  }

  return (await response.json()) as GitHubContentFile;
}

export async function createOrUpdateRepositoryFile(
  accessToken: string,
  owner: string,
  repository: string,
  path: string,
  content: string,
  commitMessage: string,
  existingSha?: string,
): Promise<GitHubFileResponse> {
  const encodedPath = path.split("/").map(encodeURIComponent).join("/");

  const body: {
    message: string;
    content: string;
    sha?: string;
  } = {
    message: commitMessage,
    content: Buffer.from(content, "utf8").toString("base64"),
  };

  if (existingSha) {
    body.sha = existingSha;
  }

  return githubRequest<GitHubFileResponse>(
    accessToken,
    `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repository)}/contents/${encodedPath}`,
    {
      method: "PUT",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify(body),
    },
  );
}
